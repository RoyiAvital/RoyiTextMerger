/// A Markdown table with aligned columns.
fn markdown_table<const N: usize>(header: [&str; N], rows: &[[String; N]]) -> String {
    let mut widths = header.map(|h| h.chars().count());
    for row in rows {
        for (w, cell) in widths.iter_mut().zip(row) {
            *w = (*w).max(cell.chars().count());
        }
    }
    let line = |cells: [&str; N]| {
        let padded: Vec<String> = cells
            .iter()
            .zip(widths)
            .map(|(c, w)| format!("{c}{}", " ".repeat(w - c.chars().count())))
            .collect();
        format!("| {} |\n", padded.join(" | "))
    };
    let mut out = line(header);
    let dashes = widths.map(|w| "-".repeat(w));
    out += &line(dashes.each_ref().map(String::as_str));
    for row in rows {
        out += &line(row.each_ref().map(String::as_str));
    }
    out
}

const C: &str = r#"#include <stdio.h>
#define MAX_$N(a, b) ((a) > (b) ? (a) : (b))
/* Block comment $N */
typedef struct node_$N { int value; struct node_$N *next; const char *name; } node_$N_t;
static inline unsigned long sum_$N(const int *values, size_t count) {
    unsigned long total = 0UL; // line comment
    for (size_t k = 0; k < count; ++k) { total += (unsigned long)values[k] * 3.5f; }
    if (total > MAX_$N(10, 20)) { printf("total=%lu\n", total); return total; }
    switch (count) { case 0: return '\0'; default: break; }
    return sizeof(node_$N_t);
}

"#;

/// `block` with `$N` = 0, 1, ... while the total stays within `size`.
fn code(block: &str, size: usize) -> Vec<u8> {
    let mut out = Vec::new();
    for n in 0.. {
        let next = block.replace("$N", &n.to_string());
        if out.len() + next.len() > size {
            break;
        }
        out.extend_from_slice(next.as_bytes());
    }
    out
}

/// `block` repeated (`$N` = 0, 1, ...) while the text stays within `count` lines.
fn lines(block: &str, count: usize) -> Vec<u8> {
    let per_block = block.matches('\n').count();
    let mut out = Vec::new();
    for n in 0..count / per_block {
        out.extend_from_slice(block.replace("$N", &n.to_string()).as_bytes());
    }
    out
}

/// `size` bytes of log lines with CRLF breaks, each line unique.
fn log(size: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(size);
    for n in 0.. {
        let line = format!(
            "2026-10-23T12:34:56.789Z INFO [worker-{}] request id={n} status=200 bytes=1234 path=/api/v1/items/{n}\r\n",
            n % 16
        );
        if out.len() + line.len() > size {
            break;
        }
        out.extend_from_slice(line.as_bytes());
    }
    out
}

/// `text` with every `every`-th line changed (the middle one of each group):
/// in turn replaced, followed by an inserted line, or removed.
fn edited(text: &[u8], every: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(text.len() + text.len() / every);
    for (i, line) in text.split_inclusive(|&b| b == b'\n').enumerate() {
        if i % every != every / 2 {
            out.extend_from_slice(line);
            continue;
        }
        let ending: &[u8] = if line.ends_with(b"\r\n") {
            b"\r\n"
        } else {
            b"\n"
        };
        match (i / every) % 3 {
            0 => {
                out.extend_from_slice(b"// changed ");
                out.extend_from_slice(line);
            }
            1 => {
                out.extend_from_slice(line);
                out.extend_from_slice(b"// inserted line");
                out.extend_from_slice(ending);
            }
            _ => {}
        }
    }
    out
}

fn fixture_dir() -> PathBuf {
    root()
        .join("target")
        .join("perf")
        .join(format!("merger-v{VERSION}"))
}

/// Generates missing or changed fixtures and verifies all hashes.
fn prepare_fixtures(print_hashes: bool) -> Result<(), String> {
    let dir = fixture_dir();
    fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let mut changed = Vec::new();
    for fixture in FIXTURES {
        let path = dir.join(fixture.name);
        let current = fs::read(&path).ok().map(|bytes| xxh3_64(&bytes));
        if !print_hashes && current == Some(fixture.hash) {
            continue;
        }
        let bytes = (fixture.generate)();
        let hash = xxh3_64(&bytes);
        if print_hashes {
            println!(
                "{:<18} {:>10} bytes  hash: 0x{hash:016x}",
                fixture.name,
                bytes.len()
            );
        } else if hash != fixture.hash {
            changed.push(format!(
                "{} (0x{hash:016x}, recorded 0x{:016x})",
                fixture.name, fixture.hash
            ));
            continue;
        }
        let mut file = fs::File::create(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        file.write_all(&bytes)
            .map_err(|e| format!("{}: {e}", path.display()))?;
    }
    if changed.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "fixtures differ from benchmark v{VERSION}: {}. Record the new hashes only while v{VERSION} is unpublished; otherwise create a new benchmark version.",
            changed.join(", ")
        ))
    }
}

/// The paths of a pair's files.
fn pair_paths((left, right): Pair) -> [PathBuf; 2] {
    let dir = fixture_dir();
    [dir.join(left), dir.join(right)]
}

struct Samples {
    first_paint: Vec<f64>,
    /// Both files read (the later one); empty without files.
    read: Vec<f64>,
    /// The first exact comparison shown; empty without files.
    compared: Vec<f64>,
    peak: Vec<f64>,
    /// Wall time of the whole test, warm-up included.
    elapsed: Duration,
}

fn run_load(exe: &Path, t: &LoadTest) -> Result<Samples, String> {
    let mut samples = Samples {
        first_paint: Vec::new(),
        read: Vec::new(),
        compared: Vec::new(),
        peak: Vec::new(),
        elapsed: Duration::ZERO,
    };
    let start = Instant::now();
    // One warm-up run (file cache, executable image), not counted.
    for run in 0..=t.runs {
        let mut command = Command::new(exe);
        command
            .args(["--trace-startup", "--exit-after-load"])
            .args(t.pair.map(pair_paths).into_iter().flatten());
        let trace = run_traced(&mut command, Duration::from_secs(10))
            .and_then(|out| parse_trace(&out))
            .map_err(|e| format!("{}: {e}", t.id))?;
        if run == 0 {
            continue;
        }
        let value = |key: &str| {
            trace
                .get(key)
                .copied()
                .ok_or_else(|| format!("{}: no {key} in the trace", t.id))
        };
        samples.first_paint.push(value("first_paint")?);
        if t.pair.is_some() {
            samples.read.push(value("file_read")?);
            samples.compared.push(value("compared")?);
        }
        samples.peak.push(value("peak_private_mib")?);
    }
    let elapsed = start.elapsed();
    if elapsed > t.cap {
        return Err(format!(
            "{} took {:.2} s, over its {} s cap",
            t.id,
            elapsed.as_secs_f64(),
            t.cap.as_secs()
        ));
    }
    samples.elapsed = elapsed;
    Ok(samples)
}

struct InputSamples {
    /// Milliseconds from handling the first step to the frame after its work.
    key_to_frame: Vec<f64>,
    peak: f64,
    elapsed: Duration,
}

fn run_input(exe: &Path, t: &InputTest) -> Result<InputSamples, String> {
    let start = Instant::now();
    let runs = t.runs + 1;
    let mut command = Command::new(exe);
    command
        .args(["--bench-keys", t.keys, "--bench-runs", &runs.to_string()])
        .args(["--bench-setup", t.setup])
        .args(pair_paths(t.pair));
    let out =
        run_traced(&mut command, Duration::from_secs(10)).map_err(|e| format!("{}: {e}", t.id))?;
    let mut first = Vec::new();
    let mut peak = None;
    for line in out.lines().map(str::trim).filter(|l| !l.is_empty()) {
        let (name, value) = line
            .strip_prefix("bench.")
            .and_then(|l| l.split_once('='))
            .ok_or_else(|| format!("{}: unexpected output line {line:?}", t.id))?;
        let value = value
            .parse::<f64>()
            .ok()
            .filter(|v| v.is_finite() && *v >= 0.0)
            .ok_or_else(|| format!("{}: invalid value in {line:?}", t.id))?;
        match name {
            "peak_private_mib" => peak = Some(value),
            "0_ms" => first.push(value),
            // Later steps, highlighted frames, the refresh period.
            _ => {}
        }
    }
    if first.len() != runs {
        return Err(format!(
            "{}: {} of {runs} repetitions reported",
            t.id,
            first.len()
        ));
    }
    // The first repetition warms up.
    first.remove(0);
    let elapsed = start.elapsed();
    if elapsed > t.cap {
        return Err(format!(
            "{} took {:.2} s, over its {} s cap",
            t.id,
            elapsed.as_secs_f64(),
            t.cap.as_secs()
        ));
    }
    Ok(InputSamples {
        key_to_frame: first,
        peak: peak.unwrap_or(0.0),
        elapsed,
    })
}

fn command_output(program: &str, args: &[&str]) -> String {
    Command::new(program)
        .args(args)
        .current_dir(root())
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .unwrap_or_else(|| "unknown".to_owned())
}

/// The options of `bench-perf`.
#[derive(Debug, PartialEq)]
struct Options {
    print_hashes: bool,
    short: bool,
    /// `--only L01,M01`: a focused subset; the total cap is not checked.
    only: Option<Vec<String>>,
}

impl Options {
    fn selected(&self, id: &str) -> bool {
        self.only
            .as_ref()
            .is_none_or(|ids| ids.iter().any(|i| i == id))
            && (!self.short || SHORT.iter().any(|r| r.id == id))
    }
}

/// Parses and checks the options before anything is built or generated:
/// unknown options or test IDs, a missing `--only` list and an empty
/// selection are errors.
fn parse_options(args: &[String]) -> Result<Options, String> {
    let mut options = Options {
        print_hashes: false,
        short: false,
        only: None,
    };
    let mut args = args.iter();
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--print-hashes" => options.print_hashes = true,
            "--short" => options.short = true,
            "--only" => {
                let list = args
                    .next()
                    .filter(|list| !list.starts_with("--"))
                    .ok_or("--only needs a comma-separated list of test IDs, e.g. L01,M01")?;
                let ids: Vec<String> = list.split(',').map(|id| id.trim().to_owned()).collect();
                let known = |id: &String| {
                    LOAD_TESTS.iter().any(|t| t.id == id) || INPUT_TESTS.iter().any(|t| t.id == id)
                };
                if let Some(id) = ids.iter().find(|id| !known(id)) {
                    return Err(format!("--only: unknown test ID {id:?}"));
                }
                options.only = Some(ids);
            }
            other => return Err(format!("unknown option {other:?}")),
        }
    }
    let mut ids = LOAD_TESTS
        .iter()
        .map(|t| t.id)
        .chain(INPUT_TESTS.iter().map(|t| t.id));
    if !options.print_hashes && !ids.any(|id| options.selected(id)) {
        return Err("--only and --short select no test together".to_owned());
    }
    Ok(options)
}

pub fn bench_perf(args: &[String]) -> ExitCode {
    let options = match parse_options(args) {
        Ok(options) => options,
        Err(e) => {
            eprintln!("bench-perf: {e}");
            return ExitCode::FAILURE;
        }
    };
    let (print_hashes, short) = (options.print_hashes, options.short);
    let selected = |id: &str| options.selected(id);
    if !print_hashes && !build_release() {
        eprintln!("release build failed");
        return ExitCode::FAILURE;
    }
    let started = Instant::now();
    if let Err(e) = prepare_fixtures(print_hashes) {
        eprintln!("{e}");
        return ExitCode::FAILURE;
    }
    if print_hashes {
        return ExitCode::SUCCESS;
    }
    let fixtures = started.elapsed();
    if fixtures > FIXTURE_CAP {
        eprintln!(
            "fixture preparation took {:.2} s, over its {} s cap",
            fixtures.as_secs_f64(),
            FIXTURE_CAP.as_secs()
        );
        return ExitCode::FAILURE;
    }
    let info = match crate::app_info() {
        Ok(info) => info,
        Err(e) => {
            eprintln!("{e}");
            return ExitCode::FAILURE;
        }
    };
    println!(
        "{} {}, Merger Performance Benchmark v{VERSION}{}, {}, {}",
        info.name,
        info.version,
        if short { " (short)" } else { "" },
        command_output("rustc", &["--version"]),
        std::env::var("PROCESSOR_IDENTIFIER").unwrap_or_default(),
    );
    println!();
    let exe = release_exe();
    let started = Instant::now();
    let mut loads = Vec::new();
    for t in LOAD_TESTS.iter().filter(|t| selected(t.id)) {
        match run_load(&exe, t) {
            Ok(samples) => loads.push((t, samples)),
            Err(e) => {
                eprintln!("{e}");
                return ExitCode::FAILURE;
            }
        }
    }
    let mut inputs = Vec::new();
    for t in INPUT_TESTS.iter().filter(|t| selected(t.id)) {
        match run_input(&exe, t) {
            Ok(samples) => inputs.push((t, samples)),
            Err(e) => {
                eprintln!("{e}");
                return ExitCode::FAILURE;
            }
        }
    }
    let total = started.elapsed();
    if short {
        print_short(&loads, &inputs);
    } else {
        print_full(&loads, &inputs);
    }
    println!();
    println!(
        "Medians. Fixtures {:.2} s; total {:.1} s (cap {} s).",
        fixtures.as_secs_f64(),
        total.as_secs_f64(),
        TOTAL_CAP.as_secs(),
    );
    if options.only.is_none() && !short && total > TOTAL_CAP {
        eprintln!("the run exceeded its {} s cap", TOTAL_CAP.as_secs());
        return ExitCode::FAILURE;
    }
    ExitCode::SUCCESS
}

fn print_full(loads: &[(&LoadTest, Samples)], inputs: &[(&InputTest, InputSamples)]) {
    if !loads.is_empty() {
        print_loads(loads);
    }
    if !loads.is_empty() && !inputs.is_empty() {
        println!();
    }
    if !inputs.is_empty() {
        print_inputs(inputs);
    }
}

fn print_loads(loads: &[(&LoadTest, Samples)]) {
    let ms = |values: &[f64]| match values {
        [] => "—".to_owned(),
        _ => format!("{:.1}", median(values)),
    };
    let rows: Vec<[String; 7]> = loads
        .iter()
        .map(|(t, s)| {
            [
                t.id.to_owned(),
                t.label.to_owned(),
                ms(&s.first_paint),
                ms(&s.read),
                ms(&s.compared),
                ms(&s.peak),
                format!("{:.2}", s.elapsed.as_secs_f64()),
            ]
        })
        .collect();
    print!(
        "{}",
        markdown_table(
            [
                "ID",
                "Test",
                "First paint [ms]",
                "Files read [ms]",
                "Compared [ms]",
                "Peak private [MiB]",
                "Time [s]",
            ],
            &rows
        )
    );
}

fn print_inputs(inputs: &[(&InputTest, InputSamples)]) {
    let rows: Vec<[String; 6]> = inputs
        .iter()
        .map(|(t, s)| {
            let mut sorted = s.key_to_frame.clone();
            sorted.sort_by(f64::total_cmp);
            [
                t.id.to_owned(),
                t.label.to_owned(),
                format!("{:.2}", median(&s.key_to_frame)),
                format!("{:.2}", percentile(&sorted, 0.95)),
                format!("{:.1}", s.peak),
                format!("{:.2}", s.elapsed.as_secs_f64()),
            ]
        })
        .collect();
    print!(
        "{}",
        markdown_table(
            [
                "ID",
                "Test",
                "Key to frame [ms]",
                "p95 [ms]",
                "Peak private [MiB]",
                "Time [s]",
            ],
            &rows
        )
    );
}

fn print_short(loads: &[(&LoadTest, Samples)], inputs: &[(&InputTest, InputSamples)]) {
    let rows: Vec<[String; 4]> = SHORT
        .iter()
        .filter_map(|r| {
            let load = loads.iter().find(|(t, _)| t.id == r.id).map(|(_, s)| s);
            let input = inputs.iter().find(|(t, _)| t.id == r.id).map(|(_, s)| s);
            // Rows of tests outside `--only` are left out.
            let (measure, result) = match (&r.measure, load, input) {
                (Measure::FirstPaint, Some(s), _) => (
                    "Time to first frame",
                    format!("{:.1} ms", median(&s.first_paint)),
                ),
                (Measure::Compared, Some(s), _) => (
                    "Time to the exact comparison",
                    format!("{:.1} ms", median(&s.compared)),
                ),
                (Measure::Peak, Some(s), _) => {
                    ("Peak memory", format!("{:.1} MiB", median(&s.peak)))
                }
                (Measure::KeyToFrame, _, Some(s)) => {
                    ("Key to frame", format!("{:.2} ms", median(&s.key_to_frame)))
                }
                _ => return None,
            };
            Some([
                r.question.to_owned(),
                r.scenario.to_owned(),
                measure.to_owned(),
                result,
            ])
        })
        .collect();
    print!(
        "{}",
        markdown_table(["Question", "Scenario", "Measure", "Result"], &rows)
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    fn parse(args: &[&str]) -> Result<Options, String> {
        parse_options(&args.iter().map(|a| a.to_string()).collect::<Vec<_>>())
    }

    #[test]
    fn options_are_checked_before_running() {
        let subset = parse(&["--only", "L01, M01"]).unwrap();
        assert_eq!(subset.only, Some(vec!["L01".to_owned(), "M01".to_owned()]));
        assert!(subset.selected("M01") && !subset.selected("L02"));
        let short = parse(&["--short", "--only", "L01,L02,N02"]).unwrap();
        assert!(short.selected("L01") && !short.selected("N02"));
        assert!(parse(&[]).unwrap().selected("R01"));
        assert!(parse(&["--print-hashes"]).unwrap().print_hashes);
        for (args, error) in [
            (&["--only", "M99"][..], "unknown test ID \"M99\""),
            (&["--only", "L01,"], "unknown test ID \"\""),
            (&["--only"], "needs a comma-separated list"),
            (&["--only", "--short"], "needs a comma-separated list"),
            (&["--short", "--only", "N02"], "select no test"),
            (&["--shrot"], "unknown option \"--shrot\""),
        ] {
            let e = parse(args).unwrap_err();
            assert!(e.contains(error), "{args:?}: {e}");
        }
    }

    #[test]
    fn generators_are_deterministic_and_sized() {
        assert_eq!(code(C, 64 * KIB), code(C, 64 * KIB));
        assert!(code(C, 64 * KIB).len() <= 64 * KIB);
        let text = log(64 * KIB);
        assert!(text.len() <= 64 * KIB && text.ends_with(b"\r\n"));
        let lines = lines(C, CHANGES_LINES);
        let count = lines.iter().filter(|&&b| b == b'\n').count();
        assert!((CHANGES_LINES - 12..=CHANGES_LINES).contains(&count));
    }

    #[test]
    fn edits_replace_insert_and_remove_lines_in_turn() {
        let text = b"0\n1\n2\n3\n4\n5\n6\n7\n8\n";
        let out = edited(text, 3);
        assert_eq!(
            String::from_utf8(out).unwrap(),
            "0\n// changed 1\n2\n3\n4\n// inserted line\n5\n6\n8\n"
        );
        let crlf = edited(b"a\r\nb\r\nc\r\nd\r\ne\r\nf\r\n", 2);
        assert!(crlf.windows(18).any(|w| w == b"// inserted line\r\n"));
    }

    #[test]
    fn short_rows_measure_existing_tests() {
        for row in SHORT {
            let load = LOAD_TESTS.iter().any(|t| t.id == row.id);
            let input = INPUT_TESTS.iter().any(|t| t.id == row.id);
            match row.measure {
                Measure::KeyToFrame => assert!(input, "{} is not an input test", row.id),
                _ => assert!(load, "{} is not a load test", row.id),
            }
        }
        for t in INPUT_TESTS {
            assert!(t.keys.split(',').all(|k| !k.trim().is_empty()), "{}", t.id);
        }
        let table = markdown_table(
            ["A", "Bb", "C"],
            &[["long cell".into(), "x".into(), "µs".into()]],
        );
        assert_eq!(
            table,
            "| A         | Bb | C  |\n| --------- | -- | -- |\n| long cell | x  | µs |\n"
        );
    }
}
