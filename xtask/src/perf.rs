//! `bench-perf`: Merger Performance Benchmark v1 (see `Performance.md`).
//!
//! Pairs of files are generated deterministically (no randomness, no clock)
//! and verified against recorded XXH3-64 hashes, so every machine measures
//! the same bytes. Load tests launch fresh release processes on a pair (or
//! without files) with `--trace-startup --exit-after-load`, which waits for
//! the first exact comparison; the application reports its stage times and
//! peak private memory. Input tests run scripted keys in the left pane once both files
//! are compared (`--bench-keys`); each step is timed from its handling to the
//! frame after its work, the comparison it starts included. The whole run
//! stays within [`TOTAL_CAP`].

